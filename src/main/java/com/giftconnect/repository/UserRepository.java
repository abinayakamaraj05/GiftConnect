package com.giftconnect.repository;

import com.giftconnect.entity.AccountStatus;
import com.giftconnect.entity.Role;
import com.giftconnect.entity.User;
import org.springframework.data.domain.Page;
import org.springframework.data.domain.Pageable;
import org.springframework.data.jpa.repository.JpaRepository;
import org.springframework.data.jpa.repository.Query;
import org.springframework.data.repository.query.Param;

import java.util.Optional;

/**
 * Data access layer for the User entity.
 * Extending JpaRepository gives us save(), findAll(), findById(), etc. for free.
 */
public interface UserRepository extends JpaRepository<User, Long> {

    /**
     * Used to check for duplicate emails during registration.
     * Spring Data JPA generates the query automatically from the method name.
     */
    Optional<User> findByEmail(String email);

    boolean existsByEmail(String email);

    /**
     * Counts accounts per role — powers the ADMIN system overview.
     * Generated by Spring Data JPA from the method name (COUNT query, no rows loaded).
     */
    long countByRole(Role role);

    /**
     * ADMIN user list with optional search (name OR email, case-insensitive),
     * optional role filter, and optional status filter — filtering and paging
     * happen in the database, never by loading the whole table into memory.
     *
     * Every parameter is nullable, so the service passes whichever filters the
     * admin actually chose (same idiom as ActivityLogRepository.findByFilters).
     */
    @Query("""
            SELECT u FROM User u
            WHERE (:search IS NULL
                   OR LOWER(u.name) LIKE LOWER(CONCAT('%', :search, '%'))
                   OR LOWER(u.email) LIKE LOWER(CONCAT('%', :search, '%')))
              AND (:role IS NULL OR u.role = :role)
              AND (:status IS NULL OR u.accountStatus = :status)
            ORDER BY u.userId ASC
            """)
    Page<User> findByFilters(@Param("search") String search,
                             @Param("role") Role role,
                             @Param("status") AccountStatus status,
                             Pageable pageable);

    /** Number of accounts in a given state — powers the system overview tiles. */
    long countByAccountStatus(AccountStatus accountStatus);

    /**
     * Counts usable accounts of one role. Used to refuse deactivating or
     * demoting the LAST active ADMIN, which would otherwise lock every
     * administrator out of the platform.
     */
    long countByRoleAndAccountStatus(Role role, AccountStatus accountStatus);
}
